import 'dart:typed_data';

import 'package:flutter/painting.dart' show Color;
import 'package:flutter_local_notifications/flutter_local_notifications.dart';

import '../logging/app_logger.dart';
import 'task_models.dart';

/// Full-screen-intent task alert (doc 9.2 / 10.1). Shown by the app itself
/// when a work order arrives over the socket while it is in the background.
///
/// Channel settings cannot change after creation. To change importance,
/// sound or vibration, bump [channelId] (`task_alert_v2`) and add the old id
/// to [_obsoleteChannelIds]; Android needs a new APK for that (doc 19.4).
class TaskNotifications {
  TaskNotifications([FlutterLocalNotificationsPlugin? plugin])
    : _plugin = plugin ?? FlutterLocalNotificationsPlugin();

  final FlutterLocalNotificationsPlugin _plugin;

  static const channelId = 'task_alert_v1';
  static const channelName = 'Penugasan Baru';
  static const _obsoleteChannelIds = <String>[];

  /// Status-bar icon: white silhouette in `res/drawable-*/ic_stat_task.png`
  /// of each app (generated by tool/icons/generate_icon_sources.ps1).
  static const smallIcon = 'ic_stat_task';

  /// Brand red (AppColors.brand); Android tints the small icon with it.
  static const accentColor = Color(0xFFE81C2C);

  /// One assignment at a time, so one stable notification id.
  static const alertNotificationId = 1001;

  /// Payload prefix of the alert notification (`task:<id>`).
  static const payloadPrefix = 'task:';

  /// 600 on, 300 off, 600 on, 1200 pause (doc 10.1).
  static final vibrationPattern = Int64List.fromList([0, 600, 300, 600, 1200]);

  static const _insistentFlag = 4; // Notification.FLAG_INSISTENT

  bool _initialized = false;

  Future<void> initialize({
    DidReceiveNotificationResponseCallback? onTap,
  }) async {
    if (_initialized) return;
    await _plugin.initialize(
      settings: const InitializationSettings(
        android: AndroidInitializationSettings(smallIcon),
        iOS: DarwinInitializationSettings(
          requestAlertPermission: false,
          requestBadgePermission: false,
          requestSoundPermission: false,
        ),
      ),
      onDidReceiveNotificationResponse: onTap,
    );
    final android = _plugin
        .resolvePlatformSpecificImplementation<
          AndroidFlutterLocalNotificationsPlugin
        >();
    if (android != null) {
      for (final id in _obsoleteChannelIds) {
        await android.deleteNotificationChannel(channelId: id);
      }
      await android.createNotificationChannel(
        AndroidNotificationChannel(
          channelId,
          channelName,
          description: 'Penugasan yang harus direspon dalam 60 detik',
          importance: Importance.max,
          playSound: true,
          enableVibration: true,
          vibrationPattern: vibrationPattern,
          audioAttributesUsage: AudioAttributesUsage.alarm,
        ),
      );
    }
    _initialized = true;
  }

  /// Requests POST_NOTIFICATIONS (Android 13+) / alert permission (iOS).
  Future<bool> requestPermission() async {
    final android = _plugin
        .resolvePlatformSpecificImplementation<
          AndroidFlutterLocalNotificationsPlugin
        >();
    if (android != null) {
      return await android.requestNotificationsPermission() ?? false;
    }
    final ios = _plugin
        .resolvePlatformSpecificImplementation<
          IOSFlutterLocalNotificationsPlugin
        >();
    if (ios != null) {
      return await ios.requestPermissions(alert: true, sound: true) ?? false;
    }
    return true;
  }

  Future<bool> areEnabled() async {
    final android = _plugin
        .resolvePlatformSpecificImplementation<
          AndroidFlutterLocalNotificationsPlugin
        >();
    if (android != null) {
      return await android.areNotificationsEnabled() ?? false;
    }
    return true;
  }

  /// Shows the alert. [remaining] auto-cancels it with the response window.
  Future<void> showTaskAlert(
    TaskAssignment task, {
    required Duration remaining,
  }) async {
    final timeoutMs = remaining.inMilliseconds.clamp(1000, 60000);
    try {
      await _plugin.show(
        id: alertNotificationId,
        title: 'Penugasan Baru - ${task.machineCode}',
        body: [
          if (task.location.isNotEmpty) task.location,
          if (task.issue.isNotEmpty) task.issue,
          'Respon dalam 1 menit.',
        ].join(' - '),
        payload: '$payloadPrefix${task.taskId}',
        notificationDetails: NotificationDetails(
          android: AndroidNotificationDetails(
            channelId,
            channelName,
            importance: Importance.max,
            priority: Priority.max,
            category: AndroidNotificationCategory.alarm,
            fullScreenIntent: true,
            timeoutAfter: timeoutMs,
            vibrationPattern: vibrationPattern,
            additionalFlags: Int32List.fromList([_insistentFlag]),
            visibility: NotificationVisibility.public,
            audioAttributesUsage: AudioAttributesUsage.alarm,
            autoCancel: true,
            icon: smallIcon,
            color: accentColor,
            ongoing: true,
          ),
          iOS: const DarwinNotificationDetails(
            presentAlert: true,
            presentSound: true,
            interruptionLevel: InterruptionLevel.timeSensitive,
          ),
        ),
      );
    } on Object catch (e, s) {
      AppLogger.error('Could not show task alert', e, s);
    }
  }

  /// Stops sound and vibration immediately (doc 10.1 "After response").
  Future<void> cancelTaskAlert() async {
    try {
      await _plugin.cancel(id: alertNotificationId);
    } on Object catch (e) {
      AppLogger.warn('Could not cancel task alert', error: e);
    }
  }

  /// Task id from the notification that launched the app, if any.
  Future<String?> launchTaskId() async {
    final details = await _plugin.getNotificationAppLaunchDetails();
    if (details == null || !details.didNotificationLaunchApp) return null;
    return taskIdFromPayload(details.notificationResponse?.payload);
  }

  static String? taskIdFromPayload(String? payload) {
    if (payload == null || !payload.startsWith(payloadPrefix)) return null;
    final id = payload.substring(payloadPrefix.length);
    return id.isEmpty ? null : id;
  }
}
